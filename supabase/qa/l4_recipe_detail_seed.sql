insert into public.recipes
  (id, user_id, title, cooking_time_minutes, ingredients, steps, notes, created_at, updated_at)
select
  ('d0000000-0000-4000-8000-0000000001' || lpad(i::text, 2, '0'))::uuid,
  u.id,
  '【L4-' || lpad((i + 6)::text, 2, '0') || '】ダミーレシピ ' || i,
  (array[5, 9, 10, 15, 19, 20, 25, 29, 30, 60, null, null])[i],
  $$材料A
