-- ---------------------------------------------------------------------------
-- 4. 投入結果の確認
-- ---------------------------------------------------------------------------

select
  r.title,
  r.cooking_time_minutes,
  r.updated_at,
  u.email as owner
from public.recipes r
join auth.users u on u.id = r.user_id
where r.title like '【L4-%'
order by r.updated_at desc;
