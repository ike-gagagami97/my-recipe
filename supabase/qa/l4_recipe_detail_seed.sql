  $$手順1
手順2$$,
  null,
  now() - (interval '1 hour' * i),
  now() - (interval '1 hour' * i)
from auth.users u
cross join generate_series(1, 12) as i
where u.email = 'CHANGE_ME@example.com'  -- ← ここも同じメールアドレスに書き換える
on conflict (id) do nothing;

